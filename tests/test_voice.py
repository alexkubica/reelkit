import json
from pathlib import Path
import sys
import tempfile
from types import SimpleNamespace
import unittest
from unittest.mock import patch

from reelkit.project import load_project
from reelkit.voice import align_words, narrate_project


class AlignmentTests(unittest.TestCase):
    def test_boundary_alignment_preserves_punctuation_and_hebrew(self):
        events = [{"text": "שלום", "offset": 1000000, "duration": 3000000},
                  {"text": "AI", "offset": 5000000, "duration": 3000000}]
        words, quality = align_words("שלום, AI!", events, 1)
        self.assertEqual(quality, "word-boundaries")
        self.assertEqual([w["text"] for w in words], ["שלום,", "AI!"])
        self.assertEqual(words[1]["start"], 0.5)

    def test_mismatched_segmentation_is_explicitly_estimated(self):
        for events in ([], [{"text": "AI", "offset": 0, "duration": 1}],
                       [{"text": "wrong", "offset": 0, "duration": 1000000}, {"text": "words", "offset": 1000000, "duration": 1000000}]):
            words, quality = align_words("שלום AI", events, 1)
            self.assertEqual(quality, "estimated")
            self.assertEqual([w["text"] for w in words], ["שלום", "AI"])
            self.assertAlmostEqual(words[-1]["end"], 1)

    def test_invalid_service_timing_falls_back(self):
        for offset, duration in ((-1, 1000000), (float("nan"), 1000000), (0, -1), (0, float("inf")), (20000000, 1000000)):
            words, quality = align_words("Hello", [{"text": "Hello", "offset": offset, "duration": duration}], 1)
            self.assertEqual(quality, "estimated")
            self.assertEqual(words, [{"text": "Hello", "start": 0.0, "end": 1.0}])


class NarrationTransactionTests(unittest.TestCase):
    def make_project(self, root, scenes):
        path = root / "project.json"
        path.write_text(json.dumps({"version": 1, "scenes": scenes}), encoding="utf-8")
        return path

    def test_success_uses_local_relative_paths_and_validates(self):
        class FakeCommunicate:
            def __init__(self, text, voice, **kwargs):
                self.text = text

            async def stream(self):
                yield {"type": "audio", "data": b"mock generated bytes"}
                for index, token in enumerate(self.text.split()):
                    yield {"type": "WordBoundary", "text": token.strip(",!"), "offset": index * 4000000, "duration": 3000000}

        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            path = self.make_project(root, [{"id": "hello", "text": "Hello, world!"}])
            with patch.dict(sys.modules, {"edge_tts": SimpleNamespace(Communicate=FakeCommunicate)}), patch("reelkit.voice.audio_duration", return_value=1.0):
                result = narrate_project(path)
            self.assertEqual(result, path.resolve())
            scene = load_project(path)["scenes"][0]
            self.assertEqual(scene["audio"], "build/voice/hello.mp3")
            self.assertEqual(scene["alignment"], "word-boundaries")
            self.assertEqual(scene["_audio"].read_bytes(), b"mock generated bytes")
            self.assertEqual([w["text"] for w in scene["words"]], ["Hello,", "world!"])

    def test_failed_second_scene_preserves_json_and_prior_generated_audio(self):
        class FailingCommunicate:
            def __init__(self, text, voice, **kwargs):
                self.text = text

            async def stream(self):
                if self.text == "Second":
                    raise ConnectionError("Service unavailable")
                yield {"type": "audio", "data": b"new audio that must not be committed"}

        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            old_audio = root / "build" / "voice" / "first.mp3"
            old_audio.parent.mkdir(parents=True)
            old_audio.write_bytes(b"keep prior audio")
            path = self.make_project(root, [{"id": "first", "text": "First", "audio": "build/voice/first.mp3"}, {"id": "second", "text": "Second"}])
            before = path.read_bytes()
            with patch.dict(sys.modules, {"edge_tts": SimpleNamespace(Communicate=FailingCommunicate)}), patch("reelkit.voice.audio_duration", return_value=1.0):
                with self.assertRaisesRegex(RuntimeError, "project JSON was not changed"):
                    narrate_project(path, force=True)
            self.assertEqual(path.read_bytes(), before)
            self.assertEqual(old_audio.read_bytes(), b"keep prior audio")
            self.assertFalse((old_audio.parent / "second.mp3").exists())

    def test_build_symlink_escape_is_rejected_before_speech(self):
        with tempfile.TemporaryDirectory() as directory, tempfile.TemporaryDirectory() as outside:
            root = Path(directory)
            try:
                (root / "build").symlink_to(Path(outside), target_is_directory=True)
            except (OSError, NotImplementedError):
                self.skipTest("Symlinks unavailable in this environment")
            path = self.make_project(root, [{"text": "Hello"}])
            before = path.read_bytes()
            service = SimpleNamespace(Communicate=lambda *args, **kwargs: self.fail("Speech must not be called"))
            with patch.dict(sys.modules, {"edge_tts": service}), self.assertRaisesRegex(ValueError, "escapes"):
                narrate_project(path)
            self.assertEqual(path.read_bytes(), before)
            self.assertEqual(list(Path(outside).iterdir()), [])

    def test_existing_audio_requires_force_and_is_not_sent(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / "voice.wav").write_bytes(b"original")
            path = self.make_project(root, [{"text": "Hello", "audio": "voice.wav"}])
            service = SimpleNamespace(Communicate=lambda *args, **kwargs: self.fail("Speech must not be called"))
            with patch.dict(sys.modules, {"edge_tts": service}), self.assertRaisesRegex(ValueError, "already has narration"):
                narrate_project(path)
            self.assertEqual((root / "voice.wav").read_bytes(), b"original")


if __name__ == "__main__":
    unittest.main()
